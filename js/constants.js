/**
 * 岩石行星的资源（按环境选，不再完全随机）。u 是 0～1 的随机数，temp 是表面温度（℃），atm 是大气，highP 是「高压行星」（超级地球 / 大型岩石行星）。
 * - 高压行星：一半概率是晶体（晶体只出现在这里）
 * - 宜居行星：水冰为主，少量稀土（有板块和火山活动）
 * - 高温（>150℃）偏金属矿和硅酸盐，有岩浆活动，稀土来自这里
 * - 温暖的岩石行星有少量火山活动（稀土 10%）；低温偏水冰
 * 熔岩行星固定金属矿、海洋世界固定水冰，由调用方另外指定。
 */
export function rockRes(u, temp, atm, highP) {
  if (highP) { if (u < .5) return '晶体'; u = (u - .5) * 2 }
  const tab = atm === '宜居' ? [['水冰', .3], ['硅酸盐', .25], ['稀土', .35], ['金属矿', .1]]
    : temp > 150 ? [['金属矿', .4], ['硅酸盐', .3], ['稀土', .3]]
    : temp > 60 ? [['硅酸盐', .45], ['金属矿', .3], ['稀土', .15], ['水冰', .1]]
    : temp > -30 ? [['硅酸盐', .4], ['金属矿', .3], ['水冰', .2], ['稀土', .1]]
    : [['水冰', .7], ['硅酸盐', .2], ['金属矿', .1]];
  let a = 0; for (const [k, w] of tab) { a += w; if (u < a) return k }
  return tab[tab.length - 1][0];
}

